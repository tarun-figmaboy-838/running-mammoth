  function toLocal(e) {
    const r = canvas.getBoundingClientRect();
    return { x: (e.clientX - r.left) * CFG.W / r.width, y: (e.clientY - r.top) * CFG.H / r.height };
  }
  let slash = null;
  function onDown(e) {
    if (paused) return;
    audio.start(); audio.resume();
    const p = toLocal(e);
    G.idle = 0; G.idleHand = 0; G.handHint = null;
    if (G.state === 'PHASE_ACTIVE') {
      slash = { pts: [p], t: 0 };
    }
    canvas.setPointerCapture && canvas.setPointerCapture(e.pointerId);
  }
  function onMove(e) {
    if (paused) return;
    const p = toLocal(e);
    atmos.pointer(p.x, p.y);
    if (slash) {
      slash.pts.push(p);
      if (slash.pts.length > 26) slash.pts.shift();
      // hit test ropes
      const L = G.l1;
      if (L && slash.pts.length > 1) {
        const a = slash.pts[slash.pts.length - 2], b = p;
        for (const sh of L.shapes) {
          if (sh.state !== 'hang') continue;
          // exactly the rope that is drawn: same two endpoints, so what looks
          // cuttable is what is cuttable
          const s2 = ropeSpan(sh);
          const top = { x: s2.x0, y: s2.y0 - 10 };
          const bot = { x: s2.x1, y: s2.y1 };
          if (segIntersect(a, b, top, bot) || nearSeg(p, top, bot, 30)) {
            slash = null; cutShape(sh); return;
          }
        }
      }
    }
  }
  function nearSeg(p, a, b, tol) {
    const vx = b.x - a.x, vy = b.y - a.y;
    const l2 = vx * vx + vy * vy || 1;
    let t = ((p.x - a.x) * vx + (p.y - a.y) * vy) / l2;
    t = clamp(t, 0, 1);
    return Math.hypot(a.x + vx * t - p.x, a.y + vy * t - p.y) < tol;
  }
  function onUp(e) {
    if (paused) { slash = null; return; }
    const p = toLocal(e);
    if (slash) slash = null;
  }
  function onKey(e) {
    if (paused) return;
    if (e.code === 'Space' || e.code === 'ArrowUp' || e.code === 'KeyW') {
      e.preventDefault(); api.jump();
    }
  }

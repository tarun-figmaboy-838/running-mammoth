  /* ---- hints ---- */
  /* Nothing here reveals an answer. The learner is never shown which shape fits or
     which corners make a diagonal — the only nudges point at WHERE the problem is
     (the hole, the corners), so the reasoning stays theirs. */
  function updateHints(dt) {
    if (G.state === 'PHASE_ACTIVE') {
      G.idle += dt;
      const L = G.l1; if (!L) return;
      // one pulse of the notch itself, so a stuck learner looks at the hole
      /* Two hints, two clocks. The pulse below resets G.idle, which meant the hand
         hint's 13s could never be reached — the pulse fired at 7s and put the
         counter back to zero, so the two guidance stages were competing for one
         timer instead of escalating. */
      G.idleHand += dt;
      if ((L.wrong >= 1 || G.idle > CFG.hint.slotMs / 1000) && L.slotPulse <= 0 && !L.pulsedOnce) {
        L.pulsedOnce = true; L.slotPulse = 1; G.idle = 0;
      }
      /* After a long idle, demonstrate the GESTURE. Placed on the middle rope, which
         is a position not an answer: it says "ropes are cut like this", never "cut
         this one". It leaves the instant anything is touched. */
      if (G.idleHand > CFG.hint.idleMs / 1000 && L.shapes.length) {
        const mid = L.shapes[Math.floor(L.shapes.length / 2)];
        G.handHint = { x: mid.anchorX, y: (L1.rigY + mid.y - (mid.h || SHAPE_H) / 2) / 2 };
      } else {
        G.handHint = null;
      }
    }
  }

  /* ---- update ---- */
  function update(dt) {
    G.t += dt; G.st += dt * 1000;
    if (G.shakeT > 0) {
      G.shakeT -= dt;
      // ease the amplitude down instead of holding full strength then cutting to zero
      G.shake = G.shakeT <= 0 ? 0 : G.shakeAmp * Math.pow(clamp(G.shakeT / G.shakeLen, 0, 1), 1.6);
    }
    if (G.quakeLen > 0 && G.quakeT < G.quakeLen) {
      G.quakeT += dt;
      G.quakeAt = G.quakeAmp * quakeEnv();
      // loose ice shaken off the path and snow jolted up around the feet. No flash:
      // firing the atmosphere pulse on this cadence was nine white flashes a second.
      G.quakeRoll = (G.quakeRoll || 0) + dt;
      if (G.quakeRoll > 0.09 && G.quakeAt > 1) {
        G.quakeRoll = 0;
        particles.chips(rand(60, CFG.W - 60), CFG.surfaceY - 4, 1, -120 - G.quakeAt * 14);
        particles.snowPuff(CFG.mammothX + rand(-80, 80), CFG.surfaceY, 1, 0.5);
      }
    } else {
      G.quakeAt = 0;
    }
    if (G.hitFx > 0) G.hitFx = Math.max(0, G.hitFx - dt * 1.5);
    if (G.verdictT > 0) { G.verdictT -= dt; if (G.verdictT <= 0) G.verdict = ''; }
    if (RUN_STATES.has(G.state) && G.speedFactor !== 1) G.speedFactor = 1;

    if (G.moving) {
      const v = CFG.runSpeed * G.speedFactor;
      G.worldX += v * dt; G.dist += v * dt;
    }
    const band = JOURNEY[G.state];
    if (band) {
      const u = clamp(G.st / band[2], 0, 1);
      G.progress = Math.max(G.progress, lerp(band[0], band[1], easeInOut(u)));
    }
    // Level 1 is six phases long, so its share of the journey advances with phases
    // repaired rather than on a per-state timer — otherwise the sky would sit still
    // through most of the game.
    if (G.phasesDone > 0 && G.phasesDone <= L1.phases.length) {
      G.progress = Math.max(G.progress, lerp(0.12, 0.82, G.phasesDone / L1.phases.length));
    }
    bgm.update(dt, G.progress);
    atmos.update(dt, G.progress);
    G.phaseLabel = bgm.label;
    mammoth.update(dt, performance.now(), G.moving && G.speedFactor > 0.2, G.speedFactor);
    particles.update(dt);
    obstacles.update(dt, G.worldX, mammoth, onCrystalHit);
    updateInstruction(dt);
    updateHints(dt);
    if (G.l1) updateL1(dt);

    switch (G.state) {
      case 'RUN_SEGMENT_1': if (G.st > T.run1) setState('JUMP_CHALLENGE_1'); break;
      case 'JUMP_CHALLENGE_1':
        if (obstacles.list.length && obstacles.list.every(o => o.passed)) setState('POST_JUMP_RUN_1');
        break;
      case 'POST_JUMP_RUN_1': if (G.st > T.postJump1) setState('GLACIER_BREAK_1'); break;
      case 'OBSTACLE_HIT':
        /* The crash runs on a timeline rather than all at once:
             0ms    impact — sparks, shake, the knockout starts
             ~1.1s  the knockout has played out and the character is down
                    -> the card pops in, and the button pops a beat after it
           Showing the panel on the frame of impact hid the animation the learner
           needs to see, which is the whole feedback. */
        if (!G.oops && G.st > T.knockout) G.oops = true;
        break;
      case 'GLACIER_BREAK_1': updateBreak(dt); break;
      case 'PHASE_INTRO':
        /* Read, then act. The panel owns the first beat by itself; when it slides
           away the ropes lower their chunks in, and only then is the phase playable. */
        if (!G.dropReady && G.st > T.introRead) {
          G.dropReady = true;
          /* Send the BANNER away, not the instruction. The panel's visibility is
             gated on instrHold, and replayInstruction() reads G.instruction — so
             clearing the text made the hint button silently do nothing for the whole
             puzzle, which is the one thing that was supposed to make clearing the
             panel safe. */
          G.instrHold = 0;
          audio.pop();
        }
        if (G.dropReady && G.st > T.introRead + T.shapeDrop + 160) setState('PHASE_ACTIVE');
        break;

      case 'PHASE_WRONG': {
        // A phase state with no puzzle built is only reachable by forcing one, but it
        // used to throw on every frame from here down, which buries the real problem
        // under a flood of errors. Bail out to play instead.
        if (!G.l1) { setState('PHASE_RUN'); break; }
        // wait for the piece to actually tip off and fade, not a fixed duration —
        // the fall is real gravity, so it takes as long as it takes
        const gone = !G.l1.shapes.some(s => s.state === 'falling' && !s.correct && s.alpha > 0.02);
        if (gone || G.st > 2200) {
          G.l1.shapes = G.l1.shapes.filter(s => !(s.state === 'falling' && !s.correct));
          mammoth.setState('LOOK_DOWN');
          // the instruction comes back so the learner is reminded what they are after
          G.instruction = phaseCfg().instruction;
          G.instrLast = '';             // re-enter, so the chips re-pop with what is left
          armInstruction(T.instructionRemind);
          setState('PHASE_ACTIVE');
        }
        break;
      }

      case 'PHASE_SUCCESS': {
        if (!G.l1) { setState('PHASE_RUN'); break; }
        // The bridge closing over is what completes a repair, so wait for that
        // rather than for a fixed time — the chunk may have had to grind along the
        // ice before it reached the hole.
        const bridged = G.l1.filled &&
          (G.gapsThisPhase || []).every(g => !g.repaired || g.bridge >= 1);
        if ((bridged && G.st > 400) || G.st > 6000) {
          // more crevasses in this phase: straight back to play. The wedged chunk has
          // already left the shape list, so nothing is culled here.
          setState(G.l1.unfilled.length ? 'PHASE_ACTIVE' : 'PHASE_DONE');
        }
        break;
      }

      case 'PHASE_DONE':
        if (G.st > T.celebrate) {
          G.l1 = null; G.gapsThisPhase = null;
          G.phase++;
          G.hitCount = 0; G.phaseJumped = false;    // a fresh phase, a fresh slate
          if (G.phase >= L1.phases.length) setState('FINAL_RUN');   // every crossing repaired
          else setState('PHASE_RUN');
        }
        break;

      case 'PHASE_RUN': {
        // a real stretch of adventure between puzzles, with a rock to clear before
        // the phases the config asks for — not before every one
        const p = L1.phases[G.phase];
        const dur = L1.runMs[G.phase] || 3000;
        if (L1.jumpBefore.includes(p.id) && !G.phaseJumped && G.st > 700) {
          G.phaseJumped = true;
          obstacles.spawn(G.worldX, 2150, 1);
          G.jumpPulse = true;
        }
        const clear = !obstacles.list.length || obstacles.list.every(o => o.passed);
        if (G.st > dur && clear) { G.jumpPulse = false; setState('GLACIER_BREAK_1'); }
        break;
      }
      case 'FINAL_RUN': if (G.progress >= 0.999) setState('COMPLETE'); break;
    }
    pushHud();
  }


  function onCrystalHit(o, sx) {
    /* Failures are counted on G, not on the obstacle. retryObstacle() clears the
       obstacle list, so a per-obstacle counter reset every retry and the 3-strike
       safety valve could never fire — a learner who could not time the jump got the
       Try Again card over and over with no way through. On the third failure the
       rock crumbles and the run simply continues. */
    G.hitCount = (G.hitCount || 0) + 1;
    if (G.hitCount >= 3) {
      audio.bonk();
      particles.snowPuff(CFG.mammothX + 50, CFG.surfaceY - 30, 7);
      particles.chips(sx, CFG.surfaceY - 20, 8, -240);
      shake(reduced ? 1.5 : 3, 220);
      G.hitFx = 1;
      o.hits = 3; o.crumble = 0;          // stops colliding and crumbles away
      mammoth.setState('HURT');            // auto-returns to RUN while moving
      return;                              // no panel, no stop: progress is guaranteed
    }
    audio.bonk();
    particles.snowPuff(CFG.mammothX + 50, CFG.surfaceY - 30, 7);
    particles.chips(CFG.mammothX + 60, CFG.surfaceY - 40, 5, -200);
    shake(reduced ? 2 : 4, 260);
    mammoth.setState('KNOCKOUT');
    mammoth.squash = 0.86;
    G.hitFx = 1;                      // drives the impact spark burst + warm vignette
    G.hitObstacle = o;
    G.hitReturn = RUN_STATES.has(G.state) ? G.state : 'RUN_SEGMENT_1';
    setState('OBSTACLE_HIT');
  }

  /** Hand control back with the obstacle on a fresh approach. Nothing is lost. */
  function retryObstacle() {
    // Clear the crystal that was walked into; re-entering the jump state spawns a
    // fresh one at the normal distance, so the run-up is identical to the first try.
    obstacles.reset();
    G.oops = false; G.hitFx = 0; G.hitObstacle = null;
    // OBSTACLE_HIT stopped the world and hid the jump button. The jump states do not
    // set these themselves — they inherit them from the run state — so restore them
    // here or the world stays frozen and the obstacle can never be passed.
    G.moving = true; G.jumpEnabled = true; G.speedFactor = 1;
    G.jumpPulse = true;               // re-teach the control on the retry
    mammoth.setState('RUN');
    setState(G.hitReturn || 'RUN_SEGMENT_1');
  }


  /* A hanging chunk of glacier, drawn in exactly the language of the shape glyph in
     the instruction panel (assets/ui/shapes/*.svg): one clean ice gradient, one navy
     outline, one white lip along the top edge.

     That match is the point. The panel says "cut the pentagon" and shows a pentagon
     drawn this way; the thing to cut is drawn the same way, so the two connect
     without the learner having to be told. The previous version had crystal facets,
     air bubbles and snow drips, which looked like ice but buried the one thing that
     actually matters here — the SILHOUETTE, which is the question being asked.

     Simple, high contrast, and lifted off the sky by its own shadow so it reads as
     an object you can reach for. `installed` adds the icicle fringe, which belongs
     on a chunk wedged under a bridge and would eat into a hanging chunk's outline. */
  /** rimMul scales the outline down when the chunk is drawn inside a magnifying
      transform, so a seated piece carries the same line weight on screen as a hanging
      one. Without it the seating scale of ~1.8 turned a 6px rim into an 11px slab. */
  function paintGlacierChunk(ctx, sh, installed, rimMul) {
    const pts = sh.pts;
    const b = polyBounds(pts);
    const scale = Math.max(1, b.w / 320);          // outline weight tracks the size
    const img = sh.art ? images['shape:' + sh.art.id] : null;

    ctx.save();
    ctx.lineJoin = 'round';
    ctx.lineCap = 'round';

    if (img) {
      /* THE DELIVERED BLOCK. Clipped to the ring as well as transformed onto it: the
         trace is a simplification of the painted edge, so a pixel or two of the
         picture can sit outside the polygon the game is using, and on a plug that has
         been swelled to span a crevasse a pixel becomes ten. Clipping means the
         silhouette on screen is exactly the silhouette being reasoned about. */
      const a = sh.art;
      ctx.save();
      if (!installed) {
        ctx.shadowColor = 'rgba(9,42,80,0.4)';
        ctx.shadowBlur = 20 * scale;
        ctx.shadowOffsetY = 9 * scale;
      }
      traceRing(ctx, pts);
      ctx.clip();
      ctx.translate(-a.off.x, -a.off.y);
      ctx.scale(a.scale, a.scale);
      ctx.rotate(a.rot);
      /* Drawn 2% OVER its box. The ring is a trace of a painted edge, so it can sit a
         fraction of a pixel outside the paint — and since the texture is clipped to the
         ring, that showed as a hairline of nothing between the picture and its rim.
         Over-drawing cannot spill, because the clip is the ring. */
      const F = 1.02;
      ctx.drawImage(img, a.box.x * F, a.box.y * F, a.box.w * F, a.box.h * F);
      ctx.restore();
    } else {
      /* No artwork for this shape: the drawn material, which is still what the basic
         PolygonFactory shapes get. */
      const g = ctx.createLinearGradient(0, b.y0, 0, b.y1);
      g.addColorStop(0, '#FBFEFF');
      g.addColorStop(0.20, '#DFF5FE');
      g.addColorStop(0.48, '#9BDCF6');
      g.addColorStop(0.78, '#41B0E4');
      g.addColorStop(1, '#1C6E9C');
      ctx.save();
      ctx.shadowColor = installed ? 'transparent' : 'rgba(9,42,80,0.4)';
      ctx.shadowBlur = installed ? 0 : 20 * scale;
      ctx.shadowOffsetY = installed ? 0 : 9 * scale;
      traceRing(ctx, pts);
      ctx.fillStyle = g;
      ctx.fill();
      ctx.restore();
    }

    /* A COLD RIM. The painted blocks carry their own bevel, so this is not an outline
       drawn around them — it is a thin frozen glow just inside the edge, which is what
       lifts a pale block off a pale sky and makes the silhouette read at a glance.
       An installed piece skips its UPPER edges: that edge has become the walking
       surface, and a line along it draws a dark seam through the snow packed over the
       join — the one line that has to be absent for a repair to read as whole. */
    const rim = (rimMul === undefined ? 1 : rimMul);
    ctx.save();
    ctx.strokeStyle = img ? 'rgba(10,140,240,0.85)' : '#14496F';
    ctx.lineWidth = (img ? 3.2 : 5.6) * scale * rim;
    if (!installed) {
      traceRing(ctx, pts);
      ctx.stroke();
    } else {
      for (let i = 0; i < pts.length; i++) {
        const a2 = pts[i], c2 = pts[(i + 1) % pts.length];
        if ((a2.y + c2.y) / 2 <= b.y0 + b.h * 0.34) continue;   // an upper edge: skip
        ctx.beginPath();
        ctx.moveTo(a2.x, a2.y); ctx.lineTo(c2.x, c2.y);
        ctx.stroke();
      }
    }
    ctx.restore();

    /* A frosted highlight along the top edges — for the DRAWN material only. The
       painted blocks carry their own bevel highlight, and adding this one on top of it
       put a thick pale bar across the upper edges, inset from them by 6% of the radius
       so it did not even follow the outline. Two highlights are worse than one. */
    if (!img) {
      ctx.strokeStyle = 'rgba(255,255,255,0.9)';
      ctx.lineWidth = 3 * scale * rim;
      for (let i = 0; i < pts.length; i++) {
        const a2 = pts[i], c2 = pts[(i + 1) % pts.length];
        if ((a2.y + c2.y) / 2 > b.y0 + b.h * 0.34) continue;      // not an upper edge
        ctx.beginPath();
        ctx.moveTo(a2.x * 0.94, a2.y * 0.94);
        ctx.lineTo(c2.x * 0.94, c2.y * 0.94);
        ctx.stroke();
      }
    }
    ctx.restore();

    if (!installed) return;
    // icicles under a wedged chunk
    let seed = (sh.seed || 1) * 17 + 91;
    const rnd = () => (seed = (seed * 9301 + 49297) % 233280) / 233280;
    ctx.save();
    ctx.fillStyle = 'rgba(236,251,255,0.95)';
    ctx.strokeStyle = 'rgba(20,73,111,0.45)';
    ctx.lineWidth = 1.6;
    for (let i = 0; i < 8; i++) {
      const u = (i + 0.5) / 8;
      const px = b.x0 + b.w * u;
      const py = ringBottomAt(pts, px);
      if (py === null) continue;
      /* Only from edges genuinely underneath. On a triangle seated point-down the
         lowest outline point near the flanks IS the top edge, so unguarded icicles
         sprouted at the snow line at both ends of the span. */
      if (py < b.y0 + b.h * 0.45) continue;
      const len = 10 + rnd() * 22;
      const hw = 3.8 + rnd() * 2.6;
      ctx.beginPath();
      ctx.moveTo(px - hw, py - 2);
      ctx.lineTo(px + hw, py - 2);
      ctx.lineTo(px, py + len);
      ctx.closePath();
      ctx.fill(); ctx.stroke();
    }
    ctx.restore();
  }

  /* FREEZING VAPOUR. A block of glacier ice hanging in the air is colder than the air,
     so it smokes: thin cold mist sliding off it and sinking. It is drawn OUTSIDE the
     ring — not clipped to it like the interior detail — because the whole point is
     that it escapes the silhouette, and it is kept faint and slow so it reads as
     atmosphere rather than as another thing to look at.

     Deterministic from the chunk's seed and the world clock, so it drifts rather than
     flickering, and it is skipped entirely under reduced motion. */
  function drawChunkVapour(ctx, sh) {
    if (reduced || !sh.art) return;
    const b = polyBounds(sh.pts);
    const n = 5;
    ctx.save();
    for (let i = 0; i < n; i++) {
      const ph = ((sh.seed || 1) * 0.37 + i * 0.71) % 1;
      // each wisp runs its own slow cycle: born at the block, sinks and fades
      const t = ((G.t * 0.22 + ph) % 1);
      const ease = t * t * (3 - 2 * t);
      const x = b.x0 + b.w * (0.14 + ((i * 0.29 + ph) % 1) * 0.72);
      const y = b.y1 - b.h * 0.1 + ease * b.h * 0.55;
      const r = b.w * (0.10 + 0.12 * ease);
      const a = Math.sin(t * Math.PI) * 0.16;
      if (a < 0.012) continue;
      const g = ctx.createRadialGradient(x, y, 0, x, y, r);
      g.addColorStop(0, 'rgba(238,251,255,' + a.toFixed(3) + ')');
      g.addColorStop(0.55, 'rgba(224,246,255,' + (a * 0.4).toFixed(3) + ')');
      g.addColorStop(1, 'rgba(224,246,255,0)');
      ctx.fillStyle = g;
      ctx.beginPath();
      ctx.ellipse(x, y, r, r * 0.52, 0, 0, 6.2832);
      ctx.fill();
    }
    ctx.restore();
  }

  /** Lowest y of a polygon's outline at a given x, or null if x misses the shape. */
  function ringBottomAt(pts, x) {
    let best = null;
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i], c = pts[(i + 1) % pts.length];
      if ((x < a.x && x < c.x) || (x > a.x && x > c.x)) continue;
      if (a.x === c.x) { if (best === null || Math.max(a.y, c.y) > best) best = Math.max(a.y, c.y); continue; }
      const t = (x - a.x) / (c.x - a.x);
      const y = a.y + (c.y - a.y) * t;
      if (best === null || y > best) best = y;
    }
    return best;
  }

  /* THE HANGING RIG.
     Each option hangs on a rope that comes down out of the fog. Three things make it
     read as genuinely hung rather than as art pasted together:

     PIVOT.  A hanging object turns until its weight is under the attachment point,
             and a rope meets it at its HIGHEST point. So the pivot is the midpoint of
             the chunk's top edge, the chunk swings about that pivot, and the rope runs
             vertically down to it. Attaching to the chunk's centre made the rope look
             glued to whichever face happened to be nearest.

     SEAMS.  The rope art has ends. The top runs off the screen and is lost in the
             fog; the bottom is buried inside the chunk. No cut-off edge is visible.

     THE CUT. When the rope is cut it really parts: the lower length falls away with
             the chunk, and the stub left above snaps upward and swings out the
             tension. Nothing about the mechanic is legible if the rope simply
             disappears. */

  /** Sway of the rig, in radians about the anchor. Shared by rope, chunk and hit test. */
  function rigSwing(sh) {
    const settle = clamp((sh.dropT - 0.5) / 2.6, 0, 1);
    const amp = lerp(reduced ? 0.014 : 0.052, reduced ? 0.004 : 0.009, settle);
    return Math.sin(G.t * 1.5 + sh.phase) * amp;
  }

  /* Where the rope attaches: the TOP CENTRE of the chunk's rotated silhouette.
     Attaching to the highest VERTEX is what a real rope would do, but a vertex sits
     off to one side on most of these shapes, so each chunk hung from a different
     corner and the row looked haphazard. Top centre keeps every rope directly above
     its own slot and the rig reads as a tidy set. */
  function chunkPivot(sh) {
    const c = Math.cos(sh.baseRot), s = Math.sin(sh.baseRot);
    /* The midpoint of the chunk's TOP EDGE — the seated edge, since chunks are built
       already seated. It used to return the shape's horizontal centre at the shape's
       topmost y, and on a tilted chunk the topmost point is a corner: the rope ended
       above the middle of the top edge with nothing there, and a corner poked up
       beside it, so every option looked as if it were dangling off one shoulder. */
    let m = null, best = Infinity;
    const pts = sh.pts || [];
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i], b = pts[(i + 1) % pts.length];
      const my = (a.y + b.y) / 2;
      if (my < best) { best = my; m = { x: (a.x + b.x) / 2, y: my }; }
    }
    if (!m) return { x: 0, y: -SHAPE_H / 2 };
    return { x: m.x * c - m.y * s, y: m.x * s + m.y * c };
  }

  /** Where the rope leaves the anchor and where it meets the chunk. */
  function ropeSpan(sh) {
    const piv = sh.pivot || chunkPivot(sh);
    return {
      x0: sh.anchorX, y0: L1.rigY,
      /* Straight down from the anchor, and that is not an approximation: the renderer
         swings the chunk ABOUT its attachment point and sh.x is then set back so the
         chunk stays in its slot, which together mean the attachment point lands on
         the anchor's x at every swing angle. Deriving x1 from sh.x instead double-
         counts the pivot offset and pulls the rope sideways. */
      x1: sh.anchorX, y1: sh.y + piv.y
    };
  }

  /* THE FOG the ropes come out of.

     This replaces an ice shelf with an icicle fringe. The shelf was the second largest
     thing on screen for the whole puzzle and it was hard scenery competing with the
     shapes; fog gives the ropes somewhere to come from without drawing the eye.

     IT IS FRACTAL NOISE, and the two attempts before it say why. A full-width linear
     gradient read as exactly what it was — a rectangle. Replacing that with a few
     dozen big soft ellipses read as horizontal bands, because a flat wide ellipse IS a
     band and no amount of stacking them hides the primitive.

     Fog has no primitive. It is turbulent at every scale at once: thick here, clear a
     hundred pixels along, wispy at the edges of both. That is what fractal noise is, so
     the alpha of this layer is four octaves of tileable value noise, contrast-stretched
     so there are genuinely clear patches and genuinely thick ones, multiplied by a
     vertical falloff.

     BUILT SMALL AND SCALED UP. The noise field is computed at a sixth of the size and
     then drawn up with smoothing — which costs a fortieth of the pixels and, more
     usefully, does the softening for free. It is cached per sky colour, so the whole
     thing is computed a handful of times over a run.

     THREE LAYERS DRIFTING AT DIFFERENT SPEEDS is what stops it reading as a texture
     pinned to the screen. Each is a strip twice the stage wide whose noise wraps in x,
     so it can be offset forever without a seam.

     TINTED BY THE SKY. A fixed white bank over a violet dusk is the exact fault that
     had generated clouds deleted from this game once already. */
  let fogArt = null;

  /** Tileable fractal value noise as an alpha field, in the sky's own colour. */
  function paintFogLayer(H, rgb, salt, cols, gain) {
    const W2 = CFG.W * 2;
    const SS = 6;
    const w = Math.max(16, Math.round(W2 / SS)), h = Math.max(6, Math.round(H / SS));
    const src = offscreen(w, h);
    const g = src.getContext('2d');
    const img = g.createImageData(w, h);
    const col = rgb.map(v => Math.round(v + (255 - v) * 0.72));

    /* Integer hash on a lattice, stable and repeatable. Every multiply goes through
       Math.imul: the classic shader-style version of this squares and cubes the seed,
       which in JS leaves float precision behind and — measured — returned exactly zero
       for 7979 of 8000 lattice points. A flat field is a flat fog, which is to say no
       fog at all. This one measures mean 0.50, sd 0.29 over the same points. */
    const hash = (ix, iy, o) => {
      let n = Math.imul(ix, 374761393) + Math.imul(iy, 668265263) +
              Math.imul(o + 1, 2246822519) + Math.imul(salt, 3266489917);
      n = Math.imul(n ^ (n >>> 13), 1274126177);
      return ((n ^ (n >>> 16)) >>> 0) / 4294967296;
    };
    const smooth = t => t * t * (3 - 2 * t);
    const octave = (u, v, c, r, o) => {
      const x = u * c, y = v * r;
      const x0 = Math.floor(x), y0 = Math.floor(y);
      const fx = smooth(x - x0), fy = smooth(y - y0);
      const wrap = i => ((i % c) + c) % c;      // wraps in x, so the strip tiles
      const a = hash(wrap(x0), y0, o), b = hash(wrap(x0 + 1), y0, o);
      const d = hash(wrap(x0), y0 + 1, o), e = hash(wrap(x0 + 1), y0 + 1, o);
      return (a * (1 - fx) + b * fx) * (1 - fy) + (d * (1 - fx) + e * fx) * fy;
    };

    for (let y = 0; y < h; y++) {
      const v = y / h;
      // thickest along the top, gone before the chunks, with a soft shoulder
      const fall = clamp(1 - Math.pow(clamp(v / 0.94, 0, 1), 1.6), 0, 1);
      for (let x = 0; x < w; x++) {
        const u = x / w;
        let n = 0, amp = 1, tot = 0, c = cols, r = 2;
        for (let o = 0; o < 4; o++) {
          n += octave(u, v, c, r, o) * amp;
          tot += amp; amp *= 0.52; c *= 2; r *= 2;
        }
        n /= tot;
        // contrast: fog is patchy, not a uniform veil
        n = clamp((n - 0.30) * 2.1, 0, 1);
        const i = (y * w + x) * 4;
        img.data[i] = col[0]; img.data[i + 1] = col[1]; img.data[i + 2] = col[2];
        img.data[i + 3] = Math.round(clamp(n * fall * gain, 0, 1) * 255);
      }
    }
    g.putImageData(img, 0, 0);

    const out = offscreen(W2, H);
    const g2 = out.getContext('2d');
    g2.imageSmoothingEnabled = true;
    g2.imageSmoothingQuality = 'high';
    g2.drawImage(src, 0, 0, W2, H);
    return out;
  }

  function drawFog(ctx) {
    const H = Math.round(L1.rigY * 1.3);
    const L = bgm ? bgm.light() : { c: [255, 255, 255], dim: 1 };
    const key = L.c.map(v => (v | 0) >> 4).join('.') + '/' + H;
    if (!fogArt || fogArt.key !== key) {
      fogArt = {
        key,
        // coarse and thick, then finer and fainter over the top of it
        layers: [
          { art: paintFogLayer(H, L.c, 1, 5, 0.95), sp: 4 },
          { art: paintFogLayer(H, L.c, 2, 9, 0.70), sp: 9 },
          { art: paintFogLayer(H, L.c, 3, 17, 0.45), sp: 17 }
        ]
      };
    }
    const W2 = CFG.W * 2;
    ctx.save();
    ctx.globalAlpha = clamp(0.5 + L.dim * 0.5, 0, 1);
    for (const l of fogArt.layers) {
      const ox = -(((reduced ? 0 : G.t) * l.sp) % W2);
      ctx.drawImage(l.art, Math.round(ox), 0);
      ctx.drawImage(l.art, Math.round(ox + W2), 0);
    }
    ctx.restore();
  }

  /* Where every rope starts: off the top of the screen, so the frame edge cuts it and
     it never has a visible end. That is what lets the fog stay a light band instead of
     having to be opaque enough to hide a rope's tip. */
  const ROPE_TOP = -24;

  function drawRope(ctx, sh) {
    const img = images.rope;
    const s = ropeSpan(sh);
    /* Over-length at both ends: the top runs off the screen behind the fog, and the
       bottom is buried inside the chunk. The lower overlap is generous because the
       chunk is MOVING while it lowers in — too tight and a gap flickers open between
       the rope and the chunk it is carrying. */
    const top = ROPE_TOP, bot = s.y1 + Math.max(30, (sh.h || SHAPE_H) * 0.3);
    const run = bot - top;
    if (run <= 4) return;
    const w = Math.max(11, (sh.w || SHAPE_W) * 0.055);
    ctx.save();
    if (img) ctx.drawImage(img, Math.round(s.x0 - w / 2), Math.round(top), Math.round(w), Math.round(run));
    else { ctx.fillStyle = 'rgba(228,246,255,0.95)'; ctx.fillRect(s.x0 - w / 2, top, w, run); }
    ctx.restore();
  }

  /* The stub left hanging on the anchor after a cut: it snaps up from the release of
     tension, then swings the energy out. */
  function drawRopeStub(ctx, st) {
    const img = images.rope;
    const e = clamp(st.t / 0.9, 0, 1);
    // snaps up as the tension goes, then keeps a visible dangling length
    const len = lerp(st.len, st.len * 0.42, easeOut(clamp(st.t / 0.22, 0, 1)));
    const swing = Math.sin(st.t * 13) * 0.22 * (1 - e);
    const w = Math.max(11, st.w * 0.055);
    /* It still SWINGS about the rig line — pivoting from the top of the screen would
       throw the tip sideways by three times as much — but it is drawn from off-screen
       upward of that, so the fog covers where it comes from. */
    const over = L1.rigY - ROPE_TOP;
    ctx.save();
    ctx.translate(st.x, L1.rigY);
    ctx.rotate(swing);
    if (img) ctx.drawImage(img, -w / 2, -over, w, len + over);
    else { ctx.fillStyle = 'rgba(228,246,255,0.95)'; ctx.fillRect(-w / 2, -over, w, len + over); }
    ctx.restore();
  }

  function drawHangingShapes(ctx, belowSurface) {
    const L = G.l1; if (!L) return;
    if (!belowSurface) {
      /* Ropes FIRST, fog over them. Every rope runs off the top of the screen, so
         what hides its upper end — and the blunt cut end of a stub — is the fog
         itself rather than a piece of scenery drawn on top of it. */
      for (const st of (L.stubs || [])) drawRopeStub(ctx, st);
      for (const sh of L.shapes) if (sh.state === 'hang') drawRope(ctx, sh);
      drawFog(ctx);
    }
    for (const sh of L.shapes) {
      const isBelow = sh.y > CFG.surfaceY - SHAPE_H * 0.4;
      if (isBelow !== belowSurface) continue;
      const piv = sh.pivot || chunkPivot(sh);
      ctx.save();
      ctx.globalAlpha = sh.alpha;
      if (isBelow) ctx.filter = `brightness(${(0.84 - (sh.submerged || 0) * 0.42).toFixed(2)})`;
      if (sh.state === 'hang') {
        // swing about the attachment point, the way a hung object does
        ctx.translate(sh.anchorX, sh.y + piv.y);
        ctx.rotate(rigSwing(sh));
        ctx.translate(-piv.x, -piv.y);
        ctx.rotate(sh.baseRot);
      } else {
        ctx.translate(sh.x, sh.y);
        ctx.rotate(sh.rot);
        ctx.scale(sh.scale, sh.scale);
      }
      paintGlacierChunk(ctx, sh, false);
      if (sh.state === 'hang') drawChunkVapour(ctx, sh);
      // the short tail of rope a cut chunk carries down with it
      if (sh.tail > 0 && sh.state !== 'hang') {
        const img = images.rope;
        const w = Math.max(11, (sh.w || SHAPE_W) * 0.055);
        ctx.save();
        ctx.translate(piv.x, piv.y);
        if (img) ctx.drawImage(img, -w / 2, -sh.tail, w, sh.tail + 10);
        ctx.restore();
      }
      ctx.restore();
      ctx.filter = 'none';
    }
    ctx.globalAlpha = 1;
  }
  // Contextual "swipe to cut" demo — drawn in neutral space between two options so it
  // teaches the gesture without pointing at an answer.
  function drawCutDemo(ctx) {
    const L = G.l1;
    if (!L || !L.demo || L.demo.done || G.attempts > 0 || G.state !== 'PHASE_ACTIVE') return;
    if (L.shapes.length < 2) return;
    // across the ropes, which is what a cut actually severs
    const cx = (L.shapes[0].x + L.shapes[1].x) / 2;
    const cy = (L1.rigY + L1.optionY - (L.shapes[0].h || SHAPE_H) / 2) / 2;
    const cycle = 0.95, u = (L.demo.t % cycle) / cycle;
    const fade = clamp(Math.sin(Math.min(u, 1) * Math.PI) * 1.6, 0, 1) * clamp(2 - L.demo.t / 1.1, 0, 1);
    if (fade <= 0.01) return;
    const x0 = cx - 100, x1 = cx + 100;
    const head = lerp(x0, x1, clamp(u * 1.25, 0, 1));
    ctx.save();
    ctx.globalAlpha = fade * 0.95;
    ctx.lineCap = 'round';
    const tr = ctx.createLinearGradient(x0, cy - 18, head, cy + 18);
    tr.addColorStop(0, 'rgba(255,255,255,0)');
    tr.addColorStop(1, 'rgba(255,255,255,0.95)');
    ctx.strokeStyle = tr; ctx.lineWidth = 8;
    ctx.beginPath(); ctx.moveTo(x0, cy - 18); ctx.lineTo(head, cy + 18); ctx.stroke();
    ctx.fillStyle = '#FFFFFF';
    ctx.beginPath(); ctx.arc(head, cy - 18 + (head - x0) / (x1 - x0) * 36, 11, 0, 6.2832); ctx.fill();
    ctx.strokeStyle = 'rgba(45,130,181,0.65)'; ctx.lineWidth = 3;
    ctx.beginPath(); ctx.arc(head, cy - 18 + (head - x0) / (x1 - x0) * 36, 11, 0, 6.2832); ctx.stroke();
    ctx.restore();
  }

  function drawSlash(ctx) {
    if (!slash || slash.pts.length < 2) return;
    ctx.save();
    ctx.lineCap = 'round'; ctx.lineJoin = 'round';
    ctx.strokeStyle = 'rgba(255,255,255,0.85)'; ctx.lineWidth = 9;
    ctx.beginPath();
    slash.pts.forEach((p, i) => i ? ctx.lineTo(p.x, p.y) : ctx.moveTo(p.x, p.y));
    ctx.stroke();
    ctx.strokeStyle = 'rgba(104,201,238,0.8)'; ctx.lineWidth = 3; ctx.stroke();
    ctx.restore();
  }
  /* THE CROSSING.
     A chunk sitting in a hole is just a chunk sitting in a hole. What makes it a
     repair is an arch: the chunk wedges in the middle of the crevasse as the
     keystone, and a snow-and-ice deck grows out from BOTH broken lips until it meets
     over the top of it. The deck is one continuous flat surface at the snow line —
     that is the thing the character runs across — and its underside dips to sit on
     the chunk, with icicles hanging beneath. `g.bridge` runs 0 -> 1 and drives the
     whole thing, so the learner watches the path knit itself back together over
     their answer.

     Earlier this drew two ramps that passed IN FRONT of the chunk and a full-width
     translucent band across the chasm, which read as a shape suspended in a hole
     behind a ghost bar — no crossing at all. */
  /* There is no deck and there are no shoulders any more. Both existed only to
     imitate the path across the gap with canvas gradients, and neither could: the
     path is bitmap art. The mend is cut from the path's own tiles instead, so there
     is nothing left for a deck to do. */

  /** The seated piece's outline in SCREEN space, so it can be used as a clip for the
      path pixels that fill it. */
  function pieceSilhouette(p, cx, cy, k, roll) {
    const c = Math.cos(roll), sn = Math.sin(roll);
    const path = new Path2D();
    p.pts.forEach((q, i) => {
      const x = cx + (q.x * c - q.y * sn) * k;
      const y = cy + (q.x * sn + q.y * c) * k;
      if (i === 0) path.moveTo(x, y); else path.lineTo(x, y);
    });
    path.closePath();
    return path;
  }

  /* The mend itself. */
  function drawKeystone(ctx, g, p) {
    if (!p) return;
    /* It SWELLS to span its slot. A chunk dropped into a chasm reads as a small block
       in a big hole however well the bridge is drawn — the answer has to visibly
       become the crossing. A little overshoot on the way makes it read as settling in
       rather than as a sprite being rescaled. */
    p.grow = clamp((p.grow || 0) + 0.055, 0, 1);
    const e = easeOut(p.grow);
    const k = lerp(1, p.fit || 1, e) * (1 + Math.sin(e * Math.PI) * 0.035);
    const sq = p.impact ? p.impact : 0;
    // it rolls from the angle it was cut at into the angle it seats at
    const roll = lerp(p.rot0 || 0, 0, e);
    /* Positioned by its TOP EDGE, not its centre, so the walking surface lands on
       the snow line at every frame of the growth and for every shape — a triangle
       and a hexagon have their flat side different distances from the bbox centre.
       SEAT_INSET tucks that edge just under the snow band laid over it. */
    const SEAT_INSET = 2;
    const kk = Math.max(k, 0.001);
    const cx = p.cx - G.worldX;
    const cy = p.topLocal !== undefined
      ? CFG.surfaceY + SEAT_INSET - p.topLocal * kk
      : p.cy;

    const gx0 = g.x0 - G.worldX, gx1 = g.x1 - G.worldX;
    const waterY = CFG.surfaceY + CFG.levelOne.waterDepth;
    const sil = pieceSilhouette(p, cx, cy, kk, roll);

    ctx.save();
    /* Two clips. The rect stops the fill at the WATER: growing the top edge out to the
       full span makes the rest of the body far bigger than the hole — a triangle's
       point reaches well past the water, a hexagon scaled to span the gap overhangs the
       path on both sides — and because the rock and the water are inside the crevasse,
       clipping to the crevasse alone does not bound any of it.

       It is the SLOT's span, not the crevasse's, so two plugs sharing one crevasse
       stay in their own lanes instead of overlapping. A slot that is the whole
       crevasse keeps the generous overhang it always had; a subdivided one butts up
       against its neighbour. */
    const px0 = (p.x0 !== undefined ? p.x0 : g.x0) - G.worldX;
    const px1 = (p.x1 !== undefined ? p.x1 : g.x1) - G.worldX;
    const pad = p.full === false ? 2 : 60;
    ctx.beginPath();
    ctx.rect(px0 - pad, CFG.surfaceY - 80, (px1 - px0) + pad * 2, waterY - CFG.surfaceY + 82);
    ctx.clip();
    /* The crevasse, UNION a band across its lips. The crevasse's top edge is chewed
       up by design and dips well below the surface in places; clipping to it alone cut
       the plug short of the walking surface exactly where the crevasse had bitten
       deepest, leaving the lip's own shadow as a dark notch in a finished repair. */
    const cavity = new Path2D();
    cavity.addPath(ground._ditchPath(gx0, gx1, g));
    cavity.rect(gx0 + 2, CFG.surfaceY - 16, (gx1 - gx0) - 4, 48);
    ctx.clip(cavity);

    /* THE OPTION'S OWN MATERIAL, unchanged. This is the learner's answer, and it has
       to stay recognisable as the thing they cut — restyling it into the path's glacier
       banding made the strata line up and lost the shape. What hides the gap is the
       snow settling over the two joins, not disguising the answer as terrain. */
    ctx.translate(cx, cy);
    ctx.rotate(roll);
    ctx.scale(kk * (1 + sq * 0.03), kk * (1 - sq * 0.05));
    // rim divided by the seating scale, so it matches a hanging chunk on screen
    paintGlacierChunk(ctx, p, true, 1 / kk);
    ctx.restore();

    // while it is still growing, frost blooms along the leading edges
    if (e < 1) {
      ctx.save();
      ctx.strokeStyle = `rgba(255,255,255,${(0.9 * (1 - e)).toFixed(3)})`;
      ctx.lineWidth = 10;
      ctx.stroke(sil);
      ctx.restore();
    }

    if (p.impact) p.impact = Math.max(0, p.impact - 0.045);
  }

  /** An offscreen canvas, for anything that is redrawn identically every frame. */
  function offscreen(w, h) {
    const c = document.createElement('canvas');
    c.width = Math.max(1, Math.ceil(w)); c.height = Math.max(1, Math.ceil(h));
    return c;
  }

  /* Deterministic hash from a world x, so no facet or icicle crawls between frames. */
  function iceHash(x, salt) {
    const v = Math.sin(x * 0.0173 + salt * 12.9898) * 43758.5453;
    return v - Math.floor(v);
  }

  /* ONE continuous snow surface over the finished crossing.
     Laid after both halves of the deck and after the keystone, so it buries every
     top edge underneath it in a single unbroken white — which is what makes the
     repair read as part of the path rather than as a piece set into a hole. It was
     previously drawn inside each half's clip, so it arrived in two short bands with
     the join still showing between them. */
  function drawCrossingSnow(ctx, g) {
    if (!(g.pieces && g.pieces.length)) return;
    const e = easeOut(clamp(g.bridge, 0, 1));
    if (e <= 0.02) return;
    const gx0 = g.x0 - G.worldX, gx1 = g.x1 - G.worldX;
    const y = CFG.surfaceY;
    // the whole span at once: the piece already reaches both lips
    const a = gx0 - 16, b = gx1 + 16;

    ctx.save();
    ctx.beginPath();
    ctx.moveTo(a, y - 11);
    ctx.lineTo(b, y - 11);
    ctx.lineTo(b, y + 5);
    // a soft, slightly uneven lower edge, so it beds in instead of sitting on top
    for (let x = b; x >= a; x -= 26) {
      ctx.quadraticCurveTo(x - 13, y + 11, x - 26, y + 5);
    }
    ctx.closePath();
    const sg = ctx.createLinearGradient(0, y - 11, 0, y + 11);
    sg.addColorStop(0, '#FFFFFF');
    sg.addColorStop(0.62, '#FFFFFF');
    sg.addColorStop(1, 'rgba(233,248,255,0.72)');
    ctx.fillStyle = sg;
    ctx.fill();

    /* Drifts heaped over EVERY join. However well two pieces of ice are fitted there
       is always a hairline where they meet; snow settling into it is both what would
       really happen and the cheapest way to make a repair look whole.

       There are two joins at the lips, and one more wherever two plugs share a
       crevasse — which is what "cut all the pentagons" produces. Those internal joins
       used to get nothing, so the seam between two plugs stayed visible, and any dip
       in a plug's top edge showed the dark crevasse through the scalloped underside
       of the snow band. */
    if (e > 0.35) {
      const heap = (e - 0.35) / 0.65;
      ctx.fillStyle = 'rgba(255,255,255,0.97)';
      const joins = [gx0, gx1];
      for (const s of (g.slots || [])) {
        const jx = s.x1 - G.worldX;
        // the last slot's far edge IS the lip, already in the list
        if (Math.abs(jx - gx1) > 2) joins.push(jx);
      }
      for (const jx of joins) {
        ctx.beginPath();
        ctx.ellipse(jx, y + 4, 42 * heap + 14, 16 * heap + 7, 0, Math.PI, 0);
        ctx.fill();
      }
    }
    ctx.restore();
  }

  function drawRepairedPieces(ctx) {
    for (const g of ground.gaps) {
      if (!(g.pieces && g.pieces.length)) continue;
      /* Every plug that has landed is drawn, whether or not the crevasse is finished
         — that is what makes a half-answered "cut all the pentagons" read as progress.
         The snow waits for the crossing to be complete, so it is the seal that says
         "done" rather than each individual piece. */
      for (const p of g.pieces) drawKeystone(ctx, g, p);
      if (g.repaired) drawCrossingSnow(ctx, g);   // last, so it buries the top join
    }
  }
  function drawCracks(ctx) {
    for (const g of ground.gaps) {
      if (g.repaired || g.crack <= 0 || g.open > 0.9) continue;
      const cx = (g.x0 + g.x1) / 2 - G.worldX;
      ctx.save();
      ctx.strokeStyle = 'rgba(20,70,120,0.85)'; ctx.lineWidth = 4; ctx.lineCap = 'round';
      ctx.beginPath();
      ctx.moveTo(cx, CFG.surfaceY - 4);
      for (let i = 0; i < g.crackPts.length; i++) {
        if ((i + 1) / g.crackPts.length > g.crack) break;
        ctx.lineTo(cx + g.crackPts[i].x, CFG.surfaceY - 4 + g.crackPts[i].y);
      }
      ctx.stroke();
      ctx.restore();
    }
  }

  function render() {
    ctx.clearRect(0, 0, CFG.W, CFG.H);
    // an impact is a random jolt; a quake is a rumble. They are different signals and
    // they are summed, so a bonk still punches through a quake.
    const sh = G.shake > 0 ? G.shake : 0;
    let ox = sh ? rand(-sh, sh) : 0, oy = sh ? rand(-sh, sh) : 0;
    const qa = G.quakeAt || 0;
    if (qa > 0.01) {
      const w = G.t * 6.2832;
      const jitter = reduced ? 0 : 0.1;
      const qx = qa * (0.62 * Math.sin(w * 7.4) + 0.28 * Math.sin(w * 13.1 + 1.7) + jitter * rand(-1, 1));
      const qy = qa * 0.52 * (0.58 * Math.sin(w * 9.3 + 0.6) + 0.30 * Math.sin(w * 17.9 + 2.2) + jitter * rand(-1, 1));
      ox += qx; oy += qy;
      G.quakeOx = qx; G.quakeOy = qy;    // readable, so the waveform can be checked
    }
    ctx.save();
    ctx.translate(ox, oy);

    // world into offscreen when focused (for blur)
    const focusing = G.focus > 0.01;
    const target = focusing ? worldCtx : ctx;
    if (focusing) { worldCtx.clearRect(0, 0, CFG.W, CFG.H); }

    bgm.draw(target, G.worldX, reduced);
    atmos.drawAurora(target, G.t, reduced);
    atmos.drawBack(target, G.worldX, G.t, reduced, bgm.light());
    ground.drawDitch(target, G.worldX, G.t);
    drawHangingShapes(target, true);
    // the pool surface closes over anything that fell into it
    ground.drawWaterFront(target, G.worldX, G.t);
    ground.draw(target, G.worldX);
    drawCracks(target);
    drawRepairedPieces(target);
    obstacles.draw(target, G.worldX, G.t);
    mammoth.draw(target, G.t);
    drawDazeStars(target);
    atmos.drawFront(target, G.worldX, G.t, reduced);

    if (focusing) {
      ctx.filter = `blur(${(6 * G.focus).toFixed(2)}px)`;
      ctx.drawImage(worldCanvas, 0, 0);
      ctx.filter = 'none';
      ctx.fillStyle = `rgba(10,44,80,${0.34 * G.focus})`;
      ctx.fillRect(0, 0, CFG.W, CFG.H);
    }
    particles.draw(ctx);
    drawHitFx(ctx);
    if (G.l1) { drawHangingShapes(ctx, false); drawCutDemo(ctx); drawSlash(ctx); }
    ctx.restore();
  }

  const worldCanvas = document.createElement('canvas');
  worldCanvas.width = CFG.W; worldCanvas.height = CFG.H;
  const worldCtx = worldCanvas.getContext('2d');

  /* ---- loop ---- */
  function frame(ts) {
    if (destroyed) return;
    raf = requestAnimationFrame(frame);
    if (!last) last = ts;
    let dt = (ts - last) / 1000; last = ts;
    if (paused) return;
    dt = Math.min(dt, 1 / 30);
    /* Fast-forward STEPS the simulation; it does not scale dt. Multiplying dt would
       give the same game time with each step that much coarser, which changes the jump
       arc and everything that depends on it — a fast-forward that quietly alters
       physics is worse than none. Rendering once per frame is what makes it cheap:
       rendering is the expensive half. */
    for (let i = 0; i < fastForward; i++) update(dt);
    render();
  }

  function resetAll() {
    G.state = 'BOOT'; G.st = 0; G.worldX = 0; G.dist = 0; G.progress = 0; G.t = 0;
    G.speedFactor = 1; G.shake = 0; G.shakeT = 0; G.moving = true; G.level = 1;
    G.instruction = ''; G.helper = ''; G.jumpEnabled = false; G.jumpPulse = false;
    G.complete = false; G.l1 = null; G.focus = 0; G.attempts = 0; G.idle = 0;
    G.phase = 0; G.phasesDone = 0; G.gapsThisPhase = null; G.phaseLayout = null; G.phaseJumped = false;
    G.oops = false; G.hitFx = 0; G.hitObstacle = null; G.hitReturn = null; G.hitCount = 0;
    G.verdict = ''; G.verdictT = 0; G.handHint = null; G.idleHand = 0; G.dropReady = false;
    G.shakeAmp = 0; G.shakeLen = 0;
    G.quakeT = 0; G.quakeAmp = 0; G.quakeLen = 0; G.quakePeak = 0; G.quakeAt = 0;
    slash = null; brk = null;
    ground.reset(); obstacles.reset(); particles.clear(); mammoth.reset(); bgm.reset();
    atmos.intensity = 0; atmos.flash = 0;
    audio.setDuck(1);
    setState('RUN_SEGMENT_1');
  }

  const api = {
    jump() {
      audio.start(); audio.resume();
      if (!G.jumpEnabled) return;
      mammoth.requestJump(performance.now());
    },
    restart() { resetAll(); },
    /** Hand over from the title/select screens into the run. */
    begin() { resetAll(); },
    /** Retry the obstacle just walked into. Never restarts the journey. */
    retryObstacle() { if (G.state === 'OBSTACLE_HIT') retryObstacle(); },
    /** The playable roster, for the selection screen. */
    roster: () => CFG.characters.map(c => ({
      id: c.id, name: c.name, tag: c.tag, blurb: c.blurb,
      theme: c.theme, theme2: c.theme2, stats: c.stats
    })),
    character: () => characterId,
    setCharacter(id) { return setCharacter(id); },
    /** Play one of the game's own sounds from the DOM screens, so the cover, the
        select screen and the HUD buttons share one palette. */
    sfx(name) { audio.start(); audio.resume(); if (typeof audio[name] === 'function') audio[name](); },
    /** A character's sheet URL + frame count, for portraits and DOM panels. */
    sheetFor(id, slot) {
      const cid = id || characterId;
      const img = images[cid + ':' + slot];
      if (!img) return null;
      const ch = CFG.characters.find(c => c.id === cid);
      return { src: img.src, frames: ch ? (ch.frames[slot] || 1) : 1 };
    },
    setPaused(v) { paused = v; if (!v) last = 0; },
    /** Sound on/off from the HUD. Returns the new state. */
    toggleSound() {
      audio.start(); audio.resume();
      audio.enabled = !audio.enabled;
      if (audio.master) audio.master.gain.setTargetAtTime(audio.enabled ? 0.5 : 0, audio.ctx.currentTime, 0.05);
      /* The bed is PAUSED, not just turned down. Muting the bus silences it, but a
         five-megabyte track left running is still being decoded for nothing. */
      if (audio.music) {
        if (audio.enabled) { const p = audio.music.el.play(); if (p && p.catch) p.catch(() => {}); }
        else audio.music.el.pause();
      }
      if (audio.enabled) audio.ui();
      return audio.enabled;
    },
    soundOn: () => !!audio.enabled,
    /** Re-show the current instruction, for a learner who has forgotten it. */
    replayInstruction() {
      if (!G.instruction) return false;
      armInstruction(T.instructionHold);
      G.instrLast = '';               // forces the banner to re-enter
      audio.ui();
      return true;
    },
    setOptions(o) {
      if (o.sound !== undefined) {
        audio.enabled = !!o.sound;
        if (audio.master) audio.master.gain.value = o.sound ? 0.5 : 0;
        if (audio.music && !o.sound) audio.music.el.pause();
      }
      if (o.reduced !== undefined) reduced = !!o.reduced || mqReduced;
      if (o.speed) CFG.runSpeed = o.speed;
      if (o.fast !== undefined) fastForward = clamp(Math.round(o.fast) || 1, 1, 8);
    },
    get paused() { return paused; },
    destroy() {
      destroyed = true; cancelAnimationFrame(raf);
      if (audio.music) { audio.music.el.pause(); audio.music.el.src = ''; }
      canvas.removeEventListener('pointerdown', onDown);
      canvas.removeEventListener('pointermove', onMove);
      window.removeEventListener('pointerup', onUp);
      window.removeEventListener('keydown', onKey);
      if (audio.ctx) audio.ctx.close();
    },
    state: () => G.state,
    /** Which animation state the character is in — handy when checking that a
        sequence (skid → tremble → look down) actually plays. */
    mammothState: () => mammoth && mammoth.state,
    mammothFrame: () => mammoth ? mammoth.lastSheet + ':' + mammoth.lastFrame : '-',
    debug: () => G,
    _ground: () => ground,
    _obstacles: () => obstacles,
    _force(s) { obstacles.reset(); setState(s); },
    /** Slice a hanging option by shape name — lets a test drive a phase to the end. */
    _cut(kind) {
      if (!G.l1) return false;
      const sh = G.l1.shapes.find(s => s.state === 'hang' && s.kind === kind);
      if (!sh) return false;
      cutShape(sh); return true;
    },
    _skipTo(ms) { G.st += ms; },
    /** Drive the character's animation state directly, for an animation audit. */
    _anim(s) { mammoth.setState(s); },
    _skid(p) { mammoth.setSkidProgress(p); },
    _player: () => mammoth,
    /** Per-frame footline measurements, so a test can check no held pose floats. */
    _footline: () => mammoth && mammoth.footline
  };

  preload().then(() => {
    if (destroyed) return;
    ground = new GroundManager(images.path);
    obstacles = new ObstacleController([images.rockWide, images.rockTall], audio, particles);
    bgm = new BackgroundTimeManager(images);
    mammoth = new PlayerController(audio, particles, currentCharacter(), images);
    mammoth.onJump = () => atmos.pulse();
    // Wait on the title/select screens rather than dropping straight into the run,
    // so PLAY reframes into gameplay instead of cutting to it. Entered BEFORE the
    // ready hook, because a host that calls begin() from onReady must win.
    setState('TITLE');
    hooks.onReady && hooks.onReady();
    raf = requestAnimationFrame(frame);
  });

  return api;
